/* global URL, console, process */
// Regenerates src/lib/wordlist/effLarge.ts from EFF's large diceware list:
//
//   curl -o eff_large_wordlist.txt https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt
//   node scripts/build-wordlist.mjs eff_large_wordlist.txt
//
// Kept so anyone can check the committed list against EFF's original. The
// input must match SOURCE_SHA256 exactly. Words containing "-" are dropped
// so the "-" separator can't make a passphrase ambiguous.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt';
const SOURCE_SHA256 = 'addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e';
const SOURCE_LINES = 7776;
const LINE = /^[1-6]{5}\t([a-z-]+)$/;
const OUTPUT = fileURLToPath(new URL('../src/lib/wordlist/effLarge.ts', import.meta.url));

const [input] = process.argv.slice(2);
if (!input) {
  console.error('Usage: node scripts/build-wordlist.mjs <eff_large_wordlist.txt>');
  process.exit(2);
}

const source = await readFile(input);
const hash = createHash('sha256').update(source).digest('hex');
if (hash !== SOURCE_SHA256) {
  console.error(`build-wordlist: ${input} has SHA-256 ${hash}, expected ${SOURCE_SHA256}`);
  process.exit(1);
}

const lines = source.toString('ascii').trimEnd().split('\n');
if (lines.length !== SOURCE_LINES) {
  console.error(`build-wordlist: expected ${SOURCE_LINES} lines, got ${lines.length}`);
  process.exit(1);
}
const words = lines.map((line, index) => {
  const match = LINE.exec(line);
  if (!match) {
    console.error(`build-wordlist: line ${index + 1} is malformed: ${JSON.stringify(line)}`);
    process.exit(1);
  }
  return match[1];
});
const kept = words.filter((word) => !word.includes('-'));

await writeFile(
  OUTPUT,
  `// Generated by scripts/build-wordlist.mjs from EFF's large word list; don't edit.
// Source: ${SOURCE_URL}
// (SHA-256 ${SOURCE_SHA256}), with the ${words.length - kept.length} hyphenated words removed.
// License: CC BY 3.0 US, Electronic Frontier Foundation; see LICENSE-EFF.txt.

export const EFF_LARGE: readonly string[] = \`
${kept.join('\n')}
\`
  .trim()
  .split('\\n');
`,
);
console.log(`build-wordlist: wrote ${kept.length} words to ${OUTPUT}`);
